"""Compute prepared-dataset statistics and figures for Phase 3.

Run from the project root:

    python scripts/dataset_statistics.py

Reads data/processed/household_objects/ (labels and metadata.json) and
writes reports/phase3_dataset_statistics.md plus bar charts under
reports/figures/. Exit code 0 on success.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = PROJECT_ROOT / "configs" / "dataset.yaml"
REPORT_PATH = PROJECT_ROOT / "reports" / "phase3_dataset_statistics.md"
FIGURES_DIR = PROJECT_ROOT / "reports" / "figures"
SPLITS = ("train", "val", "test")


def load_yaml(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a YAML mapping")
    return data


def load_classes(path: Path) -> dict[int, str]:
    data = load_yaml(path)
    class_map = {int(key): str(value) for key, value in data["classes"].items()}
    if sorted(class_map) != list(range(len(class_map))):
        raise ValueError(f"{path}: class ids must be consecutive starting at 0")
    return class_map


def collect_stats(output_dir: Path, class_map: dict[int, str]) -> dict[str, Any]:
    metadata_path = output_dir / "metadata.json"
    metadata: dict[str, Any] = {}
    if metadata_path.is_file():
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))

    split_stats: dict[str, dict[str, int]] = {}
    instances = {index: 0 for index in range(len(class_map))}
    images_with_class = {index: 0 for index in range(len(class_map))}
    per_split_class_instances = {
        split: {index: 0 for index in range(len(class_map))} for split in SPLITS
    }

    for split in SPLITS:
        labels_dir = output_dir / "labels" / split
        label_files = sorted(labels_dir.glob("*.txt")) if labels_dir.is_dir() else []
        split_instances = 0
        for label_path in label_files:
            content = label_path.read_text(encoding="utf-8").strip()
            if not content:
                continue
            present: set[int] = set()
            for line in content.splitlines():
                class_id = int(line.split()[0])
                if class_id not in class_map:
                    continue
                instances[class_id] += 1
                per_split_class_instances[split][class_id] += 1
                split_instances += 1
                present.add(class_id)
            for class_id in present:
                images_with_class[class_id] += 1
        images_dir = output_dir / "images" / split
        image_count = (
            sum(
                1
                for p in images_dir.iterdir()
                if p.suffix.lower() in {".jpg", ".jpeg", ".png"}
            )
            if images_dir.is_dir()
            else 0
        )
        split_stats[split] = {
            "images": image_count,
            "labels": len(label_files),
            "instances": split_instances,
        }

    total_images = sum(entry["images"] for entry in split_stats.values())
    total_instances = sum(entry["instances"] for entry in split_stats.values())
    counts = [instances[index] for index in range(len(class_map))]
    nonzero = [count for count in counts if count > 0]
    return {
        "splits": split_stats,
        "instances": instances,
        "images_with_class": images_with_class,
        "per_split_class_instances": per_split_class_instances,
        "totals": {"images": total_images, "instances": total_instances},
        "imbalance": {
            "max": max(nonzero) if nonzero else 0,
            "min": min(nonzero) if nonzero else 0,
            "ratio": (max(nonzero) / min(nonzero)) if nonzero else 0.0,
        },
        "metadata": metadata,
    }


def render_report(stats: dict[str, Any], class_map: dict[int, str]) -> str:
    totals = stats["totals"]
    metadata = stats["metadata"]
    lines = [
        "# Phase 3 — Prepared Dataset Statistics",
        "",
        "Generated by `python scripts/dataset_statistics.py` from the files",
        "in `data/processed/household_objects/` (all values measured).",
        "",
        "## Overview",
        "",
        f"- Total prepared images: **{totals['images']:,}**",
        f"- Total label instances: **{totals['instances']:,}**",
    ]
    for split in SPLITS:
        entry = stats["splits"][split]
        average = entry["instances"] / entry["images"] if entry["images"] else 0.0
        lines.append(
            f"- {split}: {entry['images']:,} images,"
            f" {entry['instances']:,} instances"
            f" (avg {average:.2f} objects/image)"
        )
    lines += [
        "",
        "## Instances per class",
        "",
        "| ID | Class | Instances | Share | Images containing | Max/min ratio |",
        "|---:|---|---:|---:|---:|---:|",
    ]
    imbalance = stats["imbalance"]
    total_instances = totals["instances"] or 1
    for class_id in range(len(class_map)):
        count = stats["instances"][class_id]
        share = 100.0 * count / total_instances
        lines.append(
            f"| {class_id} | {class_map[class_id]} | {count:,} | {share:.1f}% |"
            f" {stats['images_with_class'][class_id]:,} |"
            f" {count / imbalance['min'] if imbalance['min'] else 0:.1f}x |"
        )
    lines += [
        "",
        "## Class balance",
        "",
        f"- Most frequent class: {imbalance['max']:,} instances",
        f"- Least frequent class: {imbalance['min']:,} instances",
        f"- Max/min ratio: **{imbalance['ratio']:.1f}x**",
        "",
        "## Instances per class per split",
        "",
        "| Class | Train | Val | Test |",
        "|---|---:|---:|---:|",
    ]
    for class_id in range(len(class_map)):
        lines.append(
            f"| {class_map[class_id]} |"
            f" {stats['per_split_class_instances']['train'][class_id]:,} |"
            f" {stats['per_split_class_instances']['val'][class_id]:,} |"
            f" {stats['per_split_class_instances']['test'][class_id]:,} |"
        )
    if metadata:
        rejected = metadata.get("rejected_annotations", {})
        duplicates = metadata.get("duplicates_removed", {})
        lines += [
            "",
            "## Preparation metadata",
            "",
            f"- Seed: {metadata.get('seed')}, val_fraction:"
            f" {metadata.get('val_fraction')}",
            f"- Crowd annotations included:"
            f" {metadata.get('include_iscrowd')}",
            f"- Source images excluded (no valid selected-class label):"
            f" {metadata.get('source_images_excluded', 0):,}",
            f"- Rejected annotations: {json.dumps(rejected, sort_keys=True)}",
            f"- Duplicates removed: {json.dumps(duplicates, sort_keys=True)}",
            f"- Bytes copied: {metadata.get('bytes_copied', 0):,}",
        ]
    lines += [
        "",
        "## Figures",
        "",
        "- `reports/figures/phase3_class_instances.png` — instances per class",
        "- `reports/figures/phase3_split_images.png` — images per split",
        "",
    ]
    return "\n".join(lines)


def write_figures(stats: dict[str, Any], class_map: dict[int, str]) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    class_ids = list(range(len(class_map)))
    counts = [stats["instances"][index] for index in class_ids]
    order = sorted(class_ids, key=lambda index: counts[index])
    figure, axis = plt.subplots(figsize=(9, 6.5))
    axis.barh(
        [class_map[index] for index in order],
        [stats["instances"][index] for index in order],
        color="#3b7dd8",
    )
    axis.set_xlabel("Instances")
    axis.set_title("Phase 3 — instances per class")
    axis.grid(axis="x", alpha=0.3)
    figure.tight_layout()
    class_path = FIGURES_DIR / "phase3_class_instances.png"
    figure.savefig(class_path, dpi=150)
    plt.close(figure)
    written.append(class_path)

    figure, axis = plt.subplots(figsize=(6.5, 4.5))
    split_names = list(SPLITS)
    image_counts = [stats["splits"][split]["images"] for split in split_names]
    instance_counts = [stats["splits"][split]["instances"] for split in split_names]
    positions = list(range(len(split_names)))
    width = 0.38
    axis.bar(
        [p - width / 2 for p in positions], image_counts, width, label="images"
    )
    axis.bar(
        [p + width / 2 for p in positions],
        instance_counts,
        width,
        label="instances",
    )
    axis.set_xticks(positions)
    axis.set_xticklabels(split_names)
    axis.set_ylabel("Count")
    axis.set_title("Phase 3 — images and instances per split")
    axis.legend()
    axis.grid(axis="y", alpha=0.3)
    figure.tight_layout()
    split_path = FIGURES_DIR / "phase3_split_images.png"
    figure.savefig(split_path, dpi=150)
    plt.close(figure)
    written.append(split_path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument(
        "--no-figures",
        action="store_true",
        help="write only the markdown report",
    )
    args = parser.parse_args(argv)

    try:
        config = load_yaml(args.config)
        classes_path = PROJECT_ROOT / config["classes_config"]
        class_map = load_classes(classes_path)
        output_dir = PROJECT_ROOT / config["output"]["dir"]
        if not output_dir.is_dir():
            raise FileNotFoundError(f"output directory not found: {output_dir}")
        stats = collect_stats(output_dir, class_map)
    except (OSError, ValueError, KeyError) as exc:
        print(f"[FAIL] {exc}", file=sys.stderr)
        return 1

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render_report(stats, class_map), encoding="utf-8")
    print(f"[ok] wrote {REPORT_PATH.relative_to(PROJECT_ROOT)}")

    if not args.no_figures:
        try:
            figures = write_figures(stats, class_map)
        except ImportError as exc:
            print(f"[FAIL] matplotlib required for figures: {exc}", file=sys.stderr)
            return 1
        for figure in figures:
            print(f"[ok] wrote {figure.relative_to(PROJECT_ROOT)}")

    for split in SPLITS:
        entry = stats["splits"][split]
        print(
            f"[stat] {split}: {entry['images']} images,"
            f" {entry['instances']} instances"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
